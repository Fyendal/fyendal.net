import { createHash } from "node:crypto";
import { readFileSync, readdirSync, renameSync, writeFileSync } from "node:fs";
import { resolve, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = resolve(root, "packages/bot/src/generated-runtime-id.ts");
const files = [resolve(root, "pnpm-lock.yaml"), resolve(root, "tsconfig.base.json")];
function walk(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory() && entry.name !== "__tests__") walk(path);
    else if (entry.isFile() && /\.(ts|json)$/.test(entry.name)
      && !/\.test\.ts$/.test(entry.name) && path !== output) files.push(path);
  }
}
for (const name of ["shared", "protocol", "engine", "cards", "bot"]) {
  files.push(resolve(root, `packages/${name}/package.json`));
  walk(resolve(root, `packages/${name}/src`));
}
const hash = createHash("sha256");
for (const path of files.sort()) {
  hash.update(relative(root, path).split(sep).join("/"))
    .update("\0").update(readFileSync(path)).update("\0");
}
const content = `// Generated by scripts/generate-bot-runtime.mjs; never edit.\nexport const BOT_RUNTIME_ID = "${hash.digest("hex")}";\n`;
let previous;
try { previous = readFileSync(output, "utf8"); } catch { /* First build. */ }
if (previous !== content) {
  const temporary = `${output}.${process.pid}.tmp`;
  writeFileSync(temporary, content);
  renameSync(temporary, output);
}
